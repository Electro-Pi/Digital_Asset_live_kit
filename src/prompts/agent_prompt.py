def compose_instructions(
    *,
    voice: str = "female",
    catalog_index: str = "",
    prefs_context: str = "",
    base_prompt: str = "",
) -> str:
    """Assemble the system prompt for an Alawaly Real Estate voice session."""
    parts = [base_prompt or ALAWALY_SYSTEM_PROMPT]
    if catalog_index:
        parts.append(f"# ملخص الكتالوج المحدّث\n{catalog_index}")
