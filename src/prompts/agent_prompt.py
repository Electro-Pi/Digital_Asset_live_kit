def compose_instructions(
    *,
    voice: str = "female",
    catalog_index: str = "",
    prefs_context: str = "",
    base_prompt: str = "",
) -> str:
    """Assemble the full system prompt for one session.

    Order is persona → catalog → preferences, so the session-specific blocks
    read as context appended to a stable persona rather than as edits to it.
    ``base_prompt`` replaces the persona prompt; the sales optimiser uses it to
    score a candidate exactly as a live call would receive it.
    """
    parts = [base_prompt or prompt_for_voice(voice)]
    if catalog_index:
        parts.append(f"{_CATALOG_HEADER}\n{catalog_index}")
    if prefs_context:
        parts.append(prefs_context)
    return "\n".join(parts) + "\n"


