import aiohttp
import time
import logging
from livekit.agents import tts
from livekit.agents.types import DEFAULT_API_CONNECT_OPTIONS

logger = logging.getLogger(__name__)


class F5FastAPIPlugin(tts.TTS):
    def __init__(
        self,
        server_url: str = "http://localhost:8000",
        sample_rate: int = 24000,
    ):
        super().__init__(
            capabilities=tts.TTSCapabilities(streaming=False),
            sample_rate=sample_rate,
            num_channels=1,
        )
        self.server_url = server_url.rstrip("/")

    @property
    def name(self):
        return "F5-FastAPI-TTS"

    def synthesize(
        self, text: str, *, conn_options=DEFAULT_API_CONNECT_OPTIONS
    ) -> tts.ChunkedStream:
        return F5FastAPIChunkedStream(
            tts=self,
            input_text=text,
            conn_options=conn_options,
        )


class F5FastAPIChunkedStream(tts.ChunkedStream):
    def __init__(self, *, tts: F5FastAPIPlugin, input_text: str, conn_options):
        super().__init__(tts=tts, input_text=input_text, conn_options=conn_options)
        self._tts = tts
        self._audio_generated = False

    @staticmethod
    def _split_text(text: str, max_chars: int = 200) -> list[str]:
        """Splits text into chunks of at most max_chars, trying to split at separators."""
        if len(text) <= max_chars:
            return [text]

        # Priority separators (sentence ends, then clauses, then spaces)
        separators = ["。", ".", "؟", "!", "\n", "،", ",", ";", " "]
        chunks = []

        while text:
            if len(text) <= max_chars:
                chunks.append(text.strip())
                break

            # Look for the best separator within the limit
            split_at = -1
            chunk_to_check = text[:max_chars]

            for sep in separators:
                idx = chunk_to_check.rfind(sep)
                if idx > split_at:
                    split_at = idx

            if split_at != -1:
                # Include the separator in the chunk
                chunks.append(text[: split_at + 1].strip())
                text = text[split_at + 1 :]
            else:
                # No separator found, force split at max_chars
                chunks.append(text[:max_chars].strip())
                text = text[max_chars:]

        return [c for c in chunks if c]

    async def _run(self, output_emitter: tts.AudioEmitter):
        if self._audio_generated:
            return

        # Split the input text into chunks of max 200 chars
        text_chunks = self._split_text(self.input_text, max_chars=100)

        try:
            # Initialize emitter once for the whole stream
            output_emitter.initialize(
                request_id=str(id(self)),
                sample_rate=self._tts.sample_rate,
                num_channels=1,
                mime_type="audio/pcm",
            )

            async with aiohttp.ClientSession() as session:
                for chunk_text in text_chunks:
                    if not chunk_text.strip():
                        continue

                    url = f"{self._tts.server_url}/v1/audio/speech"
                    payload = {
                        "input": chunk_text,
                        "stream": True,  # Force the API to stream PCM16
                    }

                    started_at = time.perf_counter()
                    # Stream directly using aiohttp chunking
                    async with session.post(url, json=payload, timeout=120) as response:
                        response.raise_for_status()

                        # Read chunks as they are generated by FastAPI
                        async for chunk in response.content.iter_chunked(2048):
                            output_emitter.push(chunk)

                    finished_at = time.perf_counter()
                    logger.info(
                        f"Chunk processed: '{chunk_text[:30]}...' in {finished_at - started_at:.3f}s"
                    )

            output_emitter.flush()
            self._audio_generated = True

        except Exception as e:
            logger.error(f"F5TTS synthesis failed: {e}")
            raise RuntimeError(f"F5TTS synthesis failed: {str(e)}")

        finally:
            try:
                output_emitter.end_input()
            except Exception:
                pass
