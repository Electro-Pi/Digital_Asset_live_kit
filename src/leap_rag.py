# A strong local name/phrase hit is already grounded and does not benefit from
# paying for a live Gemini query embedding. Semantic retrieval remains the
# fallback for Arabic phonetic names, misspellings, sectors and activities.
LOCAL_SEMANTIC_SKIP_SCORE = 0.82
_ARABIC_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")
