def fold_text(value: str) -> str:
    """Normalize Arabic/Latin search text without changing stored answers."""
    text = unicodedata.normalize("NFKD", value or "").lower().strip()
    text = text.translate(_ARABIC_DIGITS)
    text = re.sub(r"[إأآٱ]", "ا", text)
    text = text.replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    text = text.replace("ة", "ه")
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = re.sub(r"[^\w\s.\-+]+", " ", text, flags=re.UNICODE)
    return re.sub(r"\s+", " ", text).strip()


def company_document(row: dict[str, Any]) -> str:
    """Stable multilingual document text used to build Gemini vectors."""
    parts = [
        f"Company / الشركة: {row.get('name') or ''}",
        f"Printed name: {row.get('name_raw') or ''}",
        f"Booth / الجناح: {row.get('stand') or 'not on floorplan'}",
        f"Hall / القاعة: {row.get('hall_ar') or row.get('hall') or ''}",
        f"Sector / القطاع: {row.get('sector') or ''}",
        f"Activity / النشاط: {row.get('one_liner') or ''}",
        f"Offerings / الخدمات: {row.get('offering_tags') or ''}",
        f"Pavilion: {row.get('pavilion_host') or ''}",
        f"Headquarters: {row.get('hq_city') or ''} {row.get('hq_country') or ''}",
    ]
    return "\n".join(part for part in parts if not part.endswith(": "))


def _public_company(
    row: dict[str, Any], *, score: float, retrieval: str
) -> dict[str, Any]:
    """Return only voice-safe public fields and keep the tool payload short."""
    return {
        "id": row.get("id"),
        "name": row.get("name"),
        # How the name is SAID. The model must not transliterate the Latin name
        # itself — guessing turned HAMS AI (همس) into the nonsense "هامز".
        "name_ar": row.get("name_ar"),
        "stand": row.get("stand"),
        "hall": row.get("hall"),
        "hall_ar": row.get("hall_ar"),
        "on_floorplan": bool(row.get("on_floorplan")),
        "one_liner": row.get("one_liner"),
        "sector": row.get("sector"),
        "pavilion_host": row.get("pavilion_host"),
        "hq_country": row.get("hq_country"),
        "hq_city": row.get("hq_city"),
        "saudi_presence": row.get("saudi_presence"),
        "website": row.get("website"),
        "is_official_sponsor": (
            None
            if row.get("is_official_sponsor") is None
            else bool(row.get("is_official_sponsor"))
        ),
        "score": round(float(score), 4),
        "retrieval": retrieval,
    }


