class GeminiQueryEmbedder:
    """Small async Gemini REST client with keep-alive and an in-process LRU."""

    def __init__(self, config: LeapRagConfig, cache_size: int = 256) -> None:
        self.api_key = config.gemini_api_key
        self.model = config.embedding_model
        self.dimensions = config.embedding_dimensions
        self.timeout = config.embedding_timeout_seconds
        self.cache_size = cache_size
        self._cache: OrderedDict[str, np.ndarray] = OrderedDict()
        self._client: httpx.AsyncClient | None = None
        self._client_lock = asyncio.Lock()

    @property
    def enabled(self) -> bool:
        return bool(self.api_key)

    async def _http(self) -> httpx.AsyncClient:
        if self._client is None:
            async with self._client_lock:
                if self._client is None:
                    self._client = httpx.AsyncClient(
                        timeout=httpx.Timeout(self.timeout),
                        limits=httpx.Limits(
                            max_connections=8,
                            max_keepalive_connections=4,
                            keepalive_expiry=60,
                        ),
                    )
        return self._client

    async def embed_query(self, query: str) -> np.ndarray | None:
        key = fold_text(query)
        if not key or not self.enabled:
            return None
        cached = self._cache.get(key)
        if cached is not None:
            self._cache.move_to_end(key)
            return cached

        client = await self._http()
        url = (
            "https://generativelanguage.googleapis.com/v1beta/models/"
            f"{self.model}:embedContent"
        )
        try:
            response = await client.post(
                url,
                headers={"x-goog-api-key": self.api_key},
                json={
                    "content": {"parts": [{"text": query}]},
                    "taskType": "RETRIEVAL_QUERY",
                    "outputDimensionality": self.dimensions,
                },
            )
            response.raise_for_status()
            values = response.json().get("embedding", {}).get("values")
            vector = np.asarray(values, dtype=np.float32)
            if vector.shape != (self.dimensions,):
                raise ValueError(f"unexpected embedding shape {vector.shape}")
            norm = float(np.linalg.norm(vector))
            if norm <= 0:
                raise ValueError("Gemini returned an empty embedding")
            vector /= norm
        except Exception as exc:  # network fallback must not break a live call
            status = getattr(getattr(exc, "response", None), "status_code", None)
            logger.warning(
                "LEAP semantic query unavailable model={} status={} error_type={}",
                self.model,
                status,
                type(exc).__name__,
            )
            return None

        self._cache[key] = vector
        self._cache.move_to_end(key)
        while len(self._cache) > self.cache_size:
            self._cache.popitem(last=False)
        return vector


class LocalEmbeddingIndex:
    def __init__(self, path: Path, *, model: str, dimensions: int) -> None:
        self.path = path
        self.model = model
        self.dimensions = dimensions
        self.ids: list[str] = []
        self.vectors: np.ndarray | None = None
        self.source_sha256: str | None = None
        self._load()

    @property
    def ready(self) -> bool:
        return self.vectors is not None and bool(self.ids)

    def _load(self) -> None:
        if not self.path.is_file():
            logger.warning("LEAP embedding index not found path={}", self.path)
            return
        try:
            with np.load(self.path, allow_pickle=False) as data:
                stored_model = str(data["model"].item())
                stored_dimensions = int(data["dimensions"].item())
                ids = [str(value) for value in data["ids"].tolist()]
                vectors = np.asarray(data["vectors"], dtype=np.float32)
                source_sha256 = str(data["source_sha256"].item())
            if stored_model != self.model or stored_dimensions != self.dimensions:
                raise ValueError(
                    "index configuration differs from GEMINI embedding settings"
                )
            if vectors.shape != (len(ids), self.dimensions):
                raise ValueError(f"invalid index shape {vectors.shape}")
            norms = np.linalg.norm(vectors, axis=1, keepdims=True)
            if np.any(norms <= 0):
                raise ValueError("index contains an empty vector")
            self.ids = ids
            self.vectors = vectors / norms
            self.source_sha256 = source_sha256
            logger.info(
                "LEAP embedding index loaded documents={} model={} dimensions={}",
                len(ids),
                self.model,
                self.dimensions,
            )
        except Exception as exc:
            logger.error(
                "LEAP embedding index disabled path={} error={}", self.path, exc
            )

    def top(self, query_vector: np.ndarray, limit: int = 8) -> list[tuple[str, float]]:
        if self.vectors is None or not self.ids:
            return []
        scores = self.vectors @ query_vector
        count = min(limit, len(self.ids))
        indices = np.argpartition(scores, -count)[-count:]
        ranked = sorted(indices, key=lambda i: float(scores[i]), reverse=True)
        return [(self.ids[int(i)], float(scores[int(i)])) for i in ranked]


class LeapRag:
    """Hybrid local-first exhibitor retrieval and deterministic wayfinding."""

    def __init__(self, config: LeapRagConfig | None = None) -> None:
        self.config = config or LeapRagConfig.from_env()
        self.db_path = self.config.data_dir / "03-sqlite" / "coda-leap.sqlite"
        self.graph_path = self.config.data_dir / "02-map" / "hall_graph.json"
        self.alias_path = self.config.data_dir / "02-map" / "aliases.json"
        if not self.db_path.is_file():
            raise FileNotFoundError(f"LEAP company database not found: {self.db_path}")
        if not self.graph_path.is_file():
            raise FileNotFoundError(f"LEAP hall graph not found: {self.graph_path}")

        self._db = sqlite3.connect(
            f"file:{self.db_path}?mode=ro&immutable=1",
            uri=True,
            check_same_thread=False,
        )
        self._db.row_factory = sqlite3.Row
        self._db_lock = threading.Lock()
        with self._db_lock:
            rows = [dict(row) for row in self._db.execute("SELECT * FROM companies")]
        self._companies = {str(row["id"]): row for row in rows}
        self._apply_spoken_names(rows)
        self._stand_index: dict[str, list[dict[str, Any]]] = {}
        self._name_index: dict[str, list[dict[str, Any]]] = {}
        self._folded_hay: dict[str, str] = {}
        for row in rows:
            stand = fold_text(str(row.get("stand") or ""))
            if stand:
                self._stand_index.setdefault(stand, []).append(row)
            for value in (row.get("name"), row.get("name_raw")):
                normalized = fold_text(str(value or ""))
                if normalized:
                    self._name_index.setdefault(normalized, []).append(row)
            self._folded_hay[str(row["id"])] = fold_text(
                str(row.get("search_hay") or "")
            )

        raw_aliases = json.loads(self.alias_path.read_text(encoding="utf-8"))
        if isinstance(raw_aliases, dict) and "node_aliases" in raw_aliases:
            raw_aliases = raw_aliases["node_aliases"]
        self._aliases = {
            fold_text(str(phrase)): str(node_id)
            for phrase, node_id in dict(raw_aliases).items()
        }
        self._aliases.update(
            {fold_text(phrase): node_id for phrase, node_id in _COMPANY_ALIASES.items()}
        )
        self._router = self._load_router()
        self._embedder = GeminiQueryEmbedder(self.config)
        self._embedding_index = LocalEmbeddingIndex(
            self.config.embedding_index,
            model=self.config.embedding_model,
            dimensions=self.config.embedding_dimensions,
        )
        logger.info(
            "LEAP RAG ready companies={} spoken_names={} vectors={} "
            "gemini_key_set={} data_dir={}",
            len(self._companies),
            self._named_count,
            len(self._embedding_index.ids),
            self._embedder.enabled,
            self.config.data_dir,
        )

    def _apply_spoken_names(self, rows: list[dict[str, Any]]) -> None:
        """Merge the generated spoken-Arabic names over the database rows.

        A missing file or a missing entry is not an error: that company simply
        keeps the behaviour it has today, where the model reads the Latin name
        and guesses. This file is the only thing to edit when a pronunciation is
        wrong, so a bad name is a one-line fix plus a restart.
        """
        path = self.config.data_dir / "01-companies" / NAME_AR_FILENAME
        names: dict[str, str] = {}
        if path.is_file():
            try:
                loaded = json.loads(path.read_text(encoding="utf-8"))
                if isinstance(loaded, dict):
                    names = {
                        str(k): str(v).strip()
                        for k, v in loaded.items()
                        if str(v or "").strip()
                    }
            except (ValueError, OSError) as exc:
                logger.warning("Could not read {}: {}", path, exc)
        for row in rows:
            row["name_ar"] = names.get(str(row["id"]))
        self._named_count = sum(1 for row in rows if row.get("name_ar"))

    def all_companies(self) -> list[dict[str, Any]]:
        """Every company row, for offline pack-building scripts."""
        return list(self._companies.values())

    @property
    def semantic_ready(self) -> bool:
        return self._embedder.enabled and self._embedding_index.ready

    def _load_router(self) -> Any:
        engine_path = self.config.data_dir / "04-reference" / "hall-engine.py"
        spec = importlib.util.spec_from_file_location("coda_leap_hall_engine", engine_path)
        if spec is None or spec.loader is None:
            raise RuntimeError(f"Could not load LEAP hall engine: {engine_path}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module.HallEngine(self.graph_path)

    def source_sha256(self) -> str:
        digest = hashlib.sha256()
        with self.db_path.open("rb") as source:
            for chunk in iter(lambda: source.read(1024 * 1024), b""):
                digest.update(chunk)
        return digest.hexdigest()

    def all_embedding_documents(self) -> list[tuple[str, str]]:
        return [
            (company_id, company_document(row))
            for company_id, row in sorted(self._companies.items())
        ]

    def _exact(self, query: str) -> list[dict[str, Any]]:
        folded = fold_text(query)
        if not folded:
            return []
        alias_target = self._aliases.get(folded)
        stand = fold_text(alias_target or query)
        if stand in self._stand_index:
            return self._stand_index[stand]
        if folded in self._name_index:
            return self._name_index[folded]
        return []

    def _fts(self, query: str, limit: int = 12) -> list[tuple[float, dict[str, Any]]]:
        tokens = [token for token in fold_text(query).split() if len(token) > 1]
        if not tokens:
            return []
        expression = " OR ".join(f'"{token}"*' for token in tokens[:12])
        try:
            with self._db_lock:
                rows = list(
                    self._db.execute(
                        """
                        SELECT companies.*, bm25(companies_fts) AS rank
                        FROM companies_fts
                        JOIN companies USING (id)
                        WHERE companies_fts MATCH ?
                        ORDER BY rank
                        LIMIT ?
                        """,
                        (expression, limit),
                    )
                )
        except sqlite3.Error as exc:
            logger.warning("LEAP FTS lookup failed error_type={}", type(exc).__name__)
            return []

        query_folded = fold_text(query)
        query_tokens = set(tokens)
        results: list[tuple[float, dict[str, Any]]] = []
        for position, result in enumerate(rows):
            row = dict(result)
            name = fold_text(str(row.get("name") or ""))
            hay = self._folded_hay[str(row["id"])]
            hay_tokens = set(hay.split())
            overlap = len(query_tokens & hay_tokens) / max(1, len(query_tokens))
            contains = 1.0 if query_folded and query_folded in hay else 0.0
            name_contains = 1.0 if query_folded and query_folded in name else 0.0
            score = 0.34 + (0.25 * overlap) + (0.18 * contains) + (0.18 * name_contains)
            score -= min(position, 10) * 0.006
            results.append((min(score, 0.96), row))
        return results

    async def lookup_company(self, query: str, limit: int = 5) -> dict[str, Any]:
        started = asyncio.get_running_loop().time()
        exact = self._exact(query)
        if exact:
            return {
                "ok": True,
                "query": query,
                "matches": [
                    _public_company(row, score=1.0, retrieval="exact")
                    for row in exact[:limit]
                ],
                "retrieval_ms": round(
                    (asyncio.get_running_loop().time() - started) * 1000, 1
                ),
            }

        combined: dict[str, tuple[float, dict[str, Any], str]] = {}
        lexical = self._fts(query)
        for score, row in lexical:
            combined[str(row["id"])] = (score, row, "fts")

        semantic_used = False
        strong_local_match = bool(
            lexical and lexical[0][0] >= LOCAL_SEMANTIC_SKIP_SCORE
        )
        if self.semantic_ready and not strong_local_match:
            query_vector = await self._embedder.embed_query(query)
            if query_vector is not None:
                semantic_used = True
                for company_id, similarity in self._embedding_index.top(query_vector):
                    row = self._companies.get(company_id)
                    if row is None or similarity < 0.30:
                        continue
                    current = combined.get(company_id)
                    semantic_score = max(0.0, min(0.94, similarity))
                    if current is None:
                        combined[company_id] = (semantic_score, row, "gemini")
                    else:
                        fused = min(0.98, max(current[0], semantic_score) + 0.06)
                        combined[company_id] = (fused, row, "fts+gemini")

        ranked = sorted(combined.values(), key=lambda item: item[0], reverse=True)
        matches = [
            _public_company(row, score=score, retrieval=method)
            for score, row, method in ranked[:limit]
        ]
        return {
            "ok": bool(matches),
            "query": query,
            "matches": matches,
            "semantic_used": semantic_used,
            "not_found": not bool(matches),
            "retrieval_ms": round(
                (asyncio.get_running_loop().time() - started) * 1000, 1
            ),
        }

    def _route_query(self, query: str) -> tuple[str | None, list[dict[str, Any]]]:
        """Resolve a public company/alias to a graph node before routing."""
        folded = fold_text(query)
        alias_target = self._aliases.get(folded)
        if alias_target:
            return alias_target, []
        exact = self._exact(query)
        stands = sorted({str(row["stand"]) for row in exact if row.get("stand")})
        if len(stands) == 1:
            return stands[0], []
        if len(stands) > 1:
            return None, [
                _public_company(row, score=1.0, retrieval="exact")
                for row in exact[:4]
            ]
        lexical = self._fts(query, limit=4)
        if lexical and lexical[0][0] >= 0.65 and lexical[0][1].get("stand"):
            return str(lexical[0][1]["stand"]), []
        return query, []

    def route(self, origin: str, destination: str) -> dict[str, Any]:
        resolved_origin, origin_matches = self._route_query(origin or HOME_STAND)
        if resolved_origin is None:
            return {"ok": False, "error": "origin_ambiguous", "matches": origin_matches}
        resolved_destination, destination_matches = self._route_query(destination)
        if resolved_destination is None:
            return {
                "ok": False,
                "error": "destination_ambiguous",
                "matches": destination_matches,
            }
        result = self._router.route(resolved_origin, resolved_destination)
        if not result.get("ok"):
            return result
        return {
            "ok": True,
            "origin": result.get("origin"),
            "destination": result.get("dest"),
            "meters": result.get("meters"),
            "minutes": result.get("minutes"),
            "spoken_directions_ar": result.get("speak_ar"),
            "steps": (result.get("steps") or [])[:8],
        }

    def nearest_amenity(self, origin: str, kind: str) -> dict[str, Any]:
        result = self._router.nearest_amenity(origin or HOME_STAND, kind)
        if not result.get("ok"):
            return result
        return {
            "ok": True,
            "origin": result.get("origin"),
            "destination": result.get("dest"),
            "meters": result.get("meters"),
            "minutes": result.get("minutes"),
            "spoken_directions_ar": result.get("speak_ar"),
            "steps": (result.get("steps") or [])[:8],
        }


class VisitorStore:
    """Concurrency-safe SQLite lead capture shared by warm agent processes."""

    def __init__(self, path: Path) -> None:
        self.path = path
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._initialize()

    @classmethod
    def from_env(cls) -> "VisitorStore":
        return cls(
            Path(
                os.getenv(
                    "LEAP_VISITOR_DB",
                    "/home/bassem/Coda/Call-center/data/leap-visitors.sqlite",
                )
            ).expanduser()
        )

    def _connect(self) -> sqlite3.Connection:
        connection = sqlite3.connect(self.path, timeout=3.0)
        connection.execute("PRAGMA busy_timeout=3000")
        connection.execute("PRAGMA journal_mode=WAL")
        connection.execute("PRAGMA synchronous=NORMAL")
        return connection

    def _initialize(self) -> None:
        with self._connect() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS visitors (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    session_id TEXT NOT NULL UNIQUE,
                    name TEXT NOT NULL,
                    phone_number TEXT NOT NULL,
                    phone_raw TEXT NOT NULL,
                    source TEXT NOT NULL DEFAULT 'telephone',
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                )
                """
            )
            connection.execute(
                "CREATE INDEX IF NOT EXISTS idx_visitors_phone ON visitors(phone_number)"
            )
        try:
            os.chmod(self.path, 0o600)
        except OSError:
            pass

    @staticmethod
    def normalize_name(name: str) -> str:
        clean = re.sub(r"\s+", " ", (name or "").strip())
        if len(clean) < 2 or len(clean) > 120 or not any(ch.isalpha() for ch in clean):
            raise ValueError("name_invalid")
        return clean

    @staticmethod
    def normalize_phone(phone: str) -> str:
        raw = (phone or "").translate(_ARABIC_DIGITS).strip()
        digits = re.sub(r"\D", "", raw)
        if digits.startswith("00"):
            digits = digits[2:]
        if len(digits) == 10 and digits.startswith("05"):
            digits = "966" + digits[1:]
        elif len(digits) == 9 and digits.startswith("5"):
            digits = "966" + digits
        if len(digits) < 7 or len(digits) > 15:
            raise ValueError("phone_invalid")
        return f"+{digits}"

    def save(
        self,
        session_id: str,
        name: str,
        phone: str,
        source: str = "telephone",
    ) -> dict[str, Any]:
        clean_session = re.sub(r"[^A-Za-z0-9_.:-]", "_", session_id or "")[:160]
        if not clean_session:
            raise ValueError("session_invalid")
        clean_source = (
            "telephone_test" if source == "telephone_test" else "telephone"
        )
        clean_name = self.normalize_name(name)
        clean_phone = self.normalize_phone(phone)
        raw_phone = re.sub(r"\s+", " ", (phone or "").strip())[:40]
        now = datetime.now(timezone.utc).isoformat()
        with self._connect() as connection:
            connection.execute(
                """
                INSERT INTO visitors (
                    session_id, name, phone_number, phone_raw, source,
                    created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(session_id) DO UPDATE SET
                    name=excluded.name,
                    phone_number=excluded.phone_number,
                    phone_raw=excluded.phone_raw,
                    source=excluded.source,
                    updated_at=excluded.updated_at
                """,
                (
                    clean_session,
                    clean_name,
                    clean_phone,
                    raw_phone,
                    clean_source,
                    now,
                    now,
                ),
            )
        # Do not return or log PII. The LLM only needs confirmation to advance.
        return {"saved": True, "session_id": clean_session}


def participant_channel(metadata: str | None) -> str:
    if not metadata:
        return "web"
    try:
        value = json.loads(metadata).get("channel", "web")
    except (TypeError, ValueError, AttributeError):
        return "web"
    return "telephone" if value == "telephone" else "web"


def participant_test_mode(metadata: str | None) -> bool:
    if not metadata:
        return False
    try:
        return json.loads(metadata).get("testMode") is True
    except (TypeError, ValueError, AttributeError):
        return False
