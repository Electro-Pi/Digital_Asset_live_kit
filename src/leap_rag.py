# Spoken-Arabic exhibitor names, generated by scripts/build_company_name_ar.py
# and merged over the SQLite rows at load time. It lives beside the pack rather
# than inside it because the company database is opened read-only and immutable,
# and because a pronunciation fix should not require rebuilding the pack.
