def _stable_index(*parts: str, mod: int) -> int:
    """Deterministic selection — same inputs -> same index, always."""
    if mod <= 0:
        return 0
    key = "|".join(str(p) for p in parts).encode("utf-8")
    digest = hashlib.sha256(key).hexdigest()
    return int(digest[:8], 16) % mod
